function detectLanguage() {
    const saved = localStorage.getItem('hantoor-lang');
    updateLanguage(saved || 'ar');
}

langBtn.addEventListener('click', () => {
    const nextLang = currentLang === 'en' ? 'ar' : 'en';
    const page = document.querySelector('.page');
    const mobileHero = document.querySelector('.mobile-hero');

    page.classList.add('lang-fade');
    if (mobileHero) mobileHero.classList.add('lang-fade');

    setTimeout(() => {
        updateLanguage(nextLang);
        page.classList.remove('lang-fade');
        if (mobileHero) mobileHero.classList.remove('lang-fade');
    }, 250);
});

detectLanguage();

/* ─── Sticky header offset ────────────────────── */
function updateStickyOffsets() {
    const header = document.querySelector('.site-header');
    const headerHeight = header ? header.offsetHeight : 0;

    document.documentElement.style.setProperty('--sticky-offset', (headerHeight + 12) + 'px');
}

updateStickyOffsets();
window.addEventListener('resize', updateStickyOffsets);
window.addEventListener('load', updateStickyOffsets);

/* ─── Mobile nav toggle ───────────────────────── */
const navToggle = document.getElementById('nav-toggle');
const mainNav = document.getElementById('main-nav');

if (navToggle && mainNav) {
    navToggle.addEventListener('click', () => {
        const isOpen = mainNav.classList.toggle('open');
        navToggle.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
    });

    mainNav.querySelectorAll('a').forEach((link) => {
        link.addEventListener('click', () => {
            mainNav.classList.remove('open');
            navToggle.setAttribute('aria-expanded', 'false');
        });
    });
}

/* ─── Launch confetti ─────────────────────────
   Plays once per browser session to mark the app going live. */
function launchConfetti() {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    if (sessionStorage.getItem('hantoor-launch-seen')) return;
    sessionStorage.setItem('hantoor-launch-seen', '1');

    const canvas = document.getElementById('confetti-canvas');
    if (!canvas || !canvas.getContext) return;
    const ctx = canvas.getContext('2d');
    const dpr = window.devicePixelRatio || 1;

    function resize() {
        canvas.width = window.innerWidth * dpr;
        canvas.height = window.innerHeight * dpr;
        canvas.style.width = window.innerWidth + 'px';
        canvas.style.height = window.innerHeight + 'px';
        ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    }
    resize();
    window.addEventListener('resize', resize);

    const colors = ['#59b469', '#8fe0a0', '#ffffff'];
    const pieceCount = Math.min(500, Math.round(window.innerWidth / 2));
    const pieces = [];

    for (let i = 0; i < pieceCount; i++) {
        pieces.push({
            x: Math.random() * window.innerWidth,
            y: -20 - Math.random() * window.innerHeight * 0.5,
            size: 6 + Math.random() * 8,
            color: colors[Math.floor(Math.random() * colors.length)],
            vx: (Math.random() - 0.5) * 2.4,
            vy: 4 + Math.random() * 5,
            rotation: Math.random() * 360,
            rotationSpeed: (Math.random() - 0.5) * 10,
            shape: Math.random() > 0.5 ? 'rect' : 'circle',
            opacity: 1,
        });
    }

    const duration = 4200;
    const fadeStart = duration - 700;
    const start = performance.now();

    function frame(now) {
        const elapsed = now - start;
        ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);

        let stillVisible = false;
        for (const p of pieces) {
            p.x += p.vx;
            p.y += p.vy;
            p.rotation += p.rotationSpeed;
            if (elapsed > fadeStart) p.opacity = Math.max(0, p.opacity - 0.04);
            if (p.opacity > 0 && p.y < window.innerHeight + 20) stillVisible = true;

            ctx.save();
            ctx.translate(p.x, p.y);
            ctx.rotate((p.rotation * Math.PI) / 180);
            ctx.globalAlpha = p.opacity;
            ctx.fillStyle = p.color;
            if (p.shape === 'rect') {
                ctx.fillRect(-p.size / 2, -p.size / 4, p.size, p.size / 2);
            } else {
                ctx.beginPath();
                ctx.arc(0, 0, p.size / 2, 0, Math.PI * 2);
                ctx.fill();
            }
            ctx.restore();
        }

        if (elapsed < duration && stillVisible) {
            requestAnimationFrame(frame);
        } else {
            ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);
            window.removeEventListener('resize', resize);
            canvas.style.display = 'none';
        }
    }
    requestAnimationFrame(frame);
}

if (document.readyState === 'complete') {
    launchConfetti();
} else {
    window.addEventListener('load', launchConfetti);
}
